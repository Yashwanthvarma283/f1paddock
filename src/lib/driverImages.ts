export const missingPhotos: string[] = []

export function getDriverImage(driverId: string): string | undefined {
  if (!driverId) return undefined
  const remoteUrl = driverHeadshots[driverId]
  if (!remoteUrl && import.meta.env.DEV && !missingPhotos.includes(driverId)) {
    console.warn(`DriverAvatar: Missing photo for driverId '${driverId}'`)
  }
  return remoteUrl
}
